"""Deterministic review aids for a company looking at a suggested candidate.

Pure functions over the matcher's reasons and the approved story. Nothing here
scores, ranks, filters or rejects anyone: flags are prompts for a human conversation.
"""

from __future__ import annotations

from collections import Counter
from datetime import datetime

from app.schemas import BriefView, MustHaveCheck, Reason, ReviewFlag, StorySkillOut

SHORT_EVIDENCE_WORDS = 8
SAME_TEMPLATE_MIN = 3


def must_have_checklist(brief: BriefView, reasons: list[Reason]) -> list[MustHaveCheck]:
    by_skill = {r.brief_skill: r for r in reasons if r.brief_skill and r.type != "learnable_gap"}
    rows: list[MustHaveCheck] = []
    for must in brief.must:
        reason = by_skill.get(must.label)
        if reason is not None and reason.type == "direct":
            status = "evidenced"
        elif reason is not None and reason.type == "transferable":
            status = "related"
        else:
            status = "not_evidenced"
        rows.append(
            MustHaveCheck(
                skill=must.label,
                status=status,
                seeker_skill=reason.seeker_skill if reason else None,
                evidence_quote=reason.evidence_quote
                if reason and status != "not_evidenced"
                else None,
            )
        )
    return rows


def _template(skill: StorySkillOut) -> str:
    """Quote with the skill's own name masked, to spot one sentence pattern reused per skill."""
    text = " ".join(skill.evidence_quote.lower().split())
    return text.replace(skill.label.lower(), "…")


def review_flags(skills: list[StorySkillOut], reasons: list[Reason]) -> list[ReviewFlag]:
    flags: list[ReviewFlag] = []

    for s in skills:
        if not s.seeker_confirmed:
            flags.append(
                ReviewFlag(
                    kind="unconfirmed_skill",
                    skill=s.label,
                    text=f"{s.label} was mapped by AI and not confirmed by the jobseeker.",
                )
            )
        if len(s.evidence_quote.split()) < SHORT_EVIDENCE_WORDS:
            flags.append(
                ReviewFlag(
                    kind="short_evidence",
                    skill=s.label,
                    text=f"Evidence for {s.label} is brief — ask for a concrete example.",
                )
            )

    quote_counts = Counter(s.evidence_quote.strip().lower() for s in skills)
    for quote, count in quote_counts.items():
        if count > 1:
            labels = [s.label for s in skills if s.evidence_quote.strip().lower() == quote]
            flags.append(
                ReviewFlag(
                    kind="shared_quote",
                    text=(
                        f"One sentence is the evidence for {', '.join(labels)} "
                        "— ask how each was used."
                    ),
                )
            )

    templates = Counter(_template(s) for s in skills if s.evidence_quote.strip())
    if templates and templates.most_common(1)[0][1] >= SAME_TEMPLATE_MIN:
        flags.append(
            ReviewFlag(
                kind="similar_phrasing",
                text="Several quotes use near-identical wording — ask for the real situations.",
            )
        )

    for r in reasons:
        if r.type != "consideration":
            continue
        kind = "missing_must_have" if r.brief_skill else "consideration"
        flags.append(ReviewFlag(kind=kind, skill=r.brief_skill, text=r.text))
    return flags


def provenance_notes(skills: list[StorySkillOut], approved_at: datetime | None) -> list[str]:
    confirmed = sum(1 for s in skills if s.seeker_confirmed)
    notes = [
        "Quotes are the jobseeker's own words, checked in code to be exact excerpts.",
        "Skill labels were mapped by AI from those words to a shared skills taxonomy.",
        f"The jobseeker reviewed the list and confirmed {confirmed} of {len(skills)} skills.",
        "The fit summary is generated by code from the match reasons, not by a person or an LLM.",
        "Match level uses evidenced must-have skills only, never name, age, origin or school.",
    ]
    if approved_at is not None:
        notes.insert(2, f"Story approved for sharing on {approved_at:%d %b %Y}.")
    return notes
